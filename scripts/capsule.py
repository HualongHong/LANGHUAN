#!/usr/bin/env python3
"""scripts/capsule.py — LangHuan 仓库维护胶囊工具（gen / audit / refresh）。

设计要点（窄腰原则）：
- capsule.yaml 只固化「不可从仓库推导」的内容；能用命令得到答案的一律写成查询命令（state_queries）。
- 机器只动机器区：capsule.yaml 中 ``# >>> generated`` 与 ``# <<< generated`` 标记之间的区块
  由本脚本刷新（refreshed_at / suite_version / member_count）；其余区块为人工维护区，脚本不触碰。
- HANDOFF.md 是 gen 的生成物，勿手工编辑。
- 纯标准库（Python 3.14+）。check / run 命令经 bash -c 执行（Windows Git Bash 可用），
  带超时与解码兜底；audit 不改任何文件，有失败/命令错误时退出码为 1。

用法：
    python scripts/capsule.py gen       # 刷新机器区 + 重新生成 HANDOFF.md
    python scripts/capsule.py audit     # 逐条校验 invariants 与 state_queries（只读）
    python scripts/capsule.py refresh   # 先 audit 再 gen（携带 audit 退出码）
"""

from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
import time
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CAPSULE = ROOT / "capsule.yaml"
HANDOFF = ROOT / "docs" / "HANDOFF.md"
SUITE = ROOT / "suite.yaml"
GEN_BEGIN = "# >>> generated by scripts/capsule.py — do not edit"
GEN_END = "# <<< generated"
CMD_TIMEOUT = 90


# ---------------------------------------------------------------------------
# 极简 YAML 子集解析器（仅支持本仓库 capsule.yaml / suite.yaml 用到的结构）：
#   块状映射、块状序列、序列项为映射（``- id: x`` + 续行键）、
#   纯量（纯文本 / 单引号 / 双引号带 \\\" \\\\ \\n \\t \\r 转义）、整行与行尾注释。
# ---------------------------------------------------------------------------

class YamlError(Exception):
    pass


def _strip_inline_comment(text: str) -> str:
    in_single = in_double = False
    for i, ch in enumerate(text):
        if ch == "'" and not in_double:
            in_single = not in_single
        elif ch == '"' and not in_single:
            in_double = not in_double
        elif ch == "#" and not in_single and not in_double and i > 0 and text[i - 1] in " \t":
            return text[:i]
    return text


def _parse_scalar(token: str):
    token = token.strip()
    if not token:
        return ""
    if token[0] == '"':
        out = []
        i = 1
        while i < len(token):
            ch = token[i]
            if ch == '"':
                trailing = token[i + 1:].strip()
                if trailing and not trailing.startswith("#"):
                    raise YamlError(f"引号标量后有意外内容: {token!r}")
                return "".join(out)
            if ch == "\\" and i + 1 < len(token):
                nxt = token[i + 1]
                out.append({"n": "\n", "t": "\t", "r": "\r", '"': '"', "\\": "\\", "0": "\0"}.get(nxt, nxt))
                i += 2
                continue
            out.append(ch)
            i += 1
        raise YamlError(f"未闭合的双引号标量: {token!r}")
    if token[0] == "'":
        if len(token) >= 2 and token[-1] == "'":
            return token[1:-1].replace("''", "'")
        raise YamlError(f"未闭合的单引号标量: {token!r}")
    return _strip_inline_comment(token).strip()


def _logical_lines(text: str):
    lines = []
    for raw in text.splitlines():
        stripped = raw.lstrip(" ")
        if "\t" in raw[: len(raw) - len(stripped)]:
            raise YamlError(f"缩进中不允许 tab: {raw!r}")
        content = raw.strip()
        if not content or content.startswith("#"):
            continue
        indent = len(raw) - len(stripped)
        lines.append([indent, raw[indent:].rstrip()])
    return lines


_MAP_LINE = re.compile(r"^([^:]+?):(?:\s+(.*))?$")


def _parse_map(lines, i, indent):
    node = {}
    while i < len(lines):
        ind, content = lines[i]
        if ind < indent:
            break
        if ind > indent:
            raise YamlError(f"意外缩进: {content!r}")
        if content == "-" or content.startswith("- "):
            break
        m = _MAP_LINE.match(content)
        if not m:
            raise YamlError(f"非映射行: {content!r}")
        key = m.group(1).strip()
        rest = m.group(2)
        i += 1
        if rest is not None and rest.strip():
            node[key] = _parse_scalar(rest)
        elif i < len(lines) and lines[i][0] > indent:
            node[key], i = _parse_block(lines, i, lines[i][0])
        elif i < len(lines) and lines[i][0] == indent and (
            lines[i][1] == "-" or lines[i][1].startswith("- ")
        ):
            node[key], i = _parse_list(lines, i, indent)
        else:
            node[key] = None
    return node, i


def _parse_list(lines, i, indent):
    items = []
    while i < len(lines):
        ind, content = lines[i]
        if ind != indent or not (content == "-" or content.startswith("- ")):
            break
        head = content[1:].lstrip()
        if not head:
            i += 1
            if i < len(lines) and lines[i][0] > indent:
                sub, i = _parse_block(lines, i, lines[i][0])
                items.append(sub)
            else:
                items.append(None)
            continue
        if _MAP_LINE.match(head):
            lines[i] = [indent + 2, head]  # 虚拟行：把首个键注入为映射行
            item, i = _parse_map(lines, i, indent + 2)
            items.append(item)
        else:
            items.append(_parse_scalar(head))
            i += 1
    return items, i


def _parse_block(lines, i, indent):
    if lines[i][1] == "-" or lines[i][1].startswith("- "):
        return _parse_list(lines, i, indent)
    return _parse_map(lines, i, indent)


def parse_yaml_subset(text: str):
    lines = _logical_lines(text)
    if not lines:
        return {}
    node, i = _parse_block(lines, 0, lines[0][0])
    if i != len(lines):
        raise YamlError(f"存在未消费行: {lines[i][1]!r}")
    return node


def load_capsule() -> dict:
    if not CAPSULE.exists():
        raise SystemExit(f"找不到 {CAPSULE}（本工具需在仓库根使用）")
    try:
        return parse_yaml_subset(CAPSULE.read_text(encoding="utf-8"))
    except YamlError as exc:
        raise SystemExit(f"capsule.yaml 解析失败: {exc}")


# ---------------------------------------------------------------------------
# 命令执行（bash -c；超时与解码错误优雅处理）
# ---------------------------------------------------------------------------

def run_command(cmd: str, timeout: int = CMD_TIMEOUT):
    """返回 (exit_code|None, stdout, stderr, elapsed)。exit_code=None 表示超时/启动失败。"""
    bash = shutil.which("bash")
    t0 = time.monotonic()
    kwargs = dict(cwd=ROOT, capture_output=True, timeout=timeout,
                  text=True, encoding="utf-8", errors="replace")
    try:
        if bash:
            proc = subprocess.run([bash, "-c", cmd], **kwargs)
        else:  # 兜底：非 bash 环境退化到系统 shell（Windows 下未装 Git Bash 时 check 可能不适用）
            proc = subprocess.run(cmd, shell=True, **kwargs)
        return proc.returncode, proc.stdout, proc.stderr, time.monotonic() - t0
    except subprocess.TimeoutExpired:
        return None, "", f"超时（{timeout}s）", time.monotonic() - t0
    except OSError as exc:
        return None, "", f"启动失败: {exc}", time.monotonic() - t0


# ---------------------------------------------------------------------------
# gen：刷新 capsule.yaml 机器区 + 重新生成 HANDOFF.md
# ---------------------------------------------------------------------------

def _suite_info() -> dict:
    info = {"version": "?", "members": 0}
    try:
        data = parse_yaml_subset(SUITE.read_text(encoding="utf-8"))
        suite = data.get("suite") or {}
        info["version"] = str(suite.get("version") or "?")
        info["members"] = len(data.get("members") or [])
    except Exception:
        info["members"] = len(list((ROOT / "skills").glob("*/SKILL.md")))
    return info


def refresh_generated_block(text: str, ts: str) -> str:
    lines = text.splitlines()
    if GEN_BEGIN not in lines or GEN_END not in lines:
        raise SystemExit(f"capsule.yaml 缺少机器区标记（{GEN_BEGIN} / {GEN_END}）")
    b, e = lines.index(GEN_BEGIN), lines.index(GEN_END)
    if e < b:
        raise SystemExit("capsule.yaml 机器区标记顺序错误")
    info = _suite_info()
    block = [
        GEN_BEGIN,
        "generated:",
        f'  refreshed_at: "{ts}"',
        f'  suite_version: "{info["version"]}"',
        f'  member_count: {info["members"]}',
        GEN_END,
    ]
    return "\n".join(lines[:b] + block + lines[e + 1:]) + "\n"


def _embed(text: str, max_lines: int = 120, max_chars: int = 6000) -> str:
    text = text.replace("```", "`` `")
    lines = [ln.rstrip() for ln in text.strip().splitlines()]
    truncated = False
    if len(lines) > max_lines:
        lines = lines[:max_lines]
        truncated = True
    out = "\n".join(lines)
    if len(out) > max_chars:
        out = out[:max_chars]
        truncated = True
    if truncated:
        out += "\n... （输出已截断）"
    return out or "（无输出）"


HANDOFF_TEMPLATE = """# LangHuan 套件 · 当前状态快照

> ⚠️ 本文件由 `scripts/capsule.py gen` 生成，**勿手工编辑**。
> 如需刷新：修改 `capsule.yaml` / 根 `AGENTS.md` 后重跑 `python scripts/capsule.py gen`。
> 生成时间：@TS@ ｜ 旧版手工交接文档归档于 `docs/archive/HANDOFF_legacy.md`。

## 1. 本文件回答什么问题

**仓库现在处于什么状态。** 下方第 2 节的每一小节都是 `capsule.yaml` `state_queries` 中查询命令的实时输出——本文件不固化任何结论，因此不会过时；若输出与直觉不符，以命令输出为准，并考虑增补或修正查询本身。

长期约定与规则不在此重复，直接读原文：

| 内容 | 事实来源 |
|---|---|
| 行为约束（工作流 / 环境 / 命名 / 分发形态） | 根 `AGENTS.md` |
| 套件身份、可验证不变量、写入协议、冻结流程 | `capsule.yaml`（`identity` / `invariants` / `protocols` / `freeze`） |
| 历史决策与过程记录 | `docs/DEV_LOG.md`（只增不改） |

## 2. 当前状态（查询命令实时输出）

@STATE@
## 3. 新会话接手步骤

1. 跑 `python scripts/capsule.py audit` —— 不变量全过再继续；
2. 读根 `AGENTS.md` 与 `capsule.yaml`（身份 / 不变量 / 协议 / 冻结流程）；
3. 需要历史细节时检索 `docs/DEV_LOG.md`，不要从头通读。
"""

HANDOFF_QUERY_TEMPLATE = """### 2.@IDX@ @ID@ — @ASK@

命令：`@RUN@`

```text
@OUTPUT@
```

"""


def _write_if_changed(path: Path, content: str) -> bool:
    old = path.read_text(encoding="utf-8") if path.exists() else None
    if old == content:
        return False
    path.write_text(content, encoding="utf-8")
    return True


def cmd_gen() -> int:
    capsule_text = CAPSULE.read_text(encoding="utf-8")
    data = parse_yaml_subset(capsule_text)
    queries = data.get("state_queries") or []
    ts = datetime.now().isoformat(timespec="seconds")

    sections = []
    for idx, q in enumerate(queries, 1):
        rc, out, err, _dur = run_command(q["run"])
        body = out
        if rc != 0:
            detail = f"[命令退出码 {rc}]" if rc is not None else ""
            body = (out + ("\n" if out else "") + f"{detail} {err.strip()}").strip()
        sections.append(
            HANDOFF_QUERY_TEMPLATE.replace("@IDX@", str(idx))
            .replace("@ID@", str(q["id"]))
            .replace("@ASK@", str(q["ask"]))
            .replace("@RUN@", str(q["run"]))
            .replace("@OUTPUT@", _embed(body))
        )
    handoff = HANDOFF_TEMPLATE.replace("@TS@", ts).replace("@STATE@", "\n".join(sections))
    changed = _write_if_changed(HANDOFF, handoff)
    print(f"HANDOFF.md: {'已重新生成' if changed else '无变化'}")

    new_text = refresh_generated_block(capsule_text, ts)
    if new_text != capsule_text:
        CAPSULE.write_text(new_text, encoding="utf-8")
        print("capsule.yaml: 机器区已刷新（人工维护区未触碰）")
    else:
        print("capsule.yaml: 机器区无变化")
    return 0


# ---------------------------------------------------------------------------
# audit：逐条执行 invariants.check 与 state_queries.run（只读）
# ---------------------------------------------------------------------------

def _indent(text: str, prefix: str = "    ") -> str:
    return "\n".join(prefix + ln for ln in text.strip().splitlines())


def cmd_audit() -> int:
    data = load_capsule()
    invs = data.get("invariants") or []
    queries = data.get("state_queries") or []
    print(f"capsule audit — {len(invs)} 条不变量 + {len(queries)} 条状态查询（只读，不改任何文件）\n")

    failures = 0

    print("== invariants ==")
    for inv in invs:
        rc, out, err, dur = run_command(inv["check"])
        if rc == 0:
            print(f"[PASS] {inv['id']} ({dur:.1f}s)")
            continue
        failures += 1
        if rc is None:
            print(f"[ERR ] {inv['id']} — 命令错误：{err.strip()}")
        else:
            print(f"[FAIL] {inv['id']} — 退出码 {rc}")
            detail = (out + err).strip()
            if detail:
                print(_indent(detail[:800]))

    print("\n== state_queries ==")
    for q in queries:
        rc, out, err, dur = run_command(q["run"])
        if rc == 0:
            print(f"[OK  ] {q['id']} ({dur:.1f}s)")
            continue
        failures += 1
        if rc is None:
            print(f"[ERR ] {q['id']} — 命令错误：{err.strip()}")
        else:
            print(f"[ERR ] {q['id']} — 命令退出码 {rc}")
            detail = (out + err).strip()
            if detail:
                print(_indent(detail[:800]))

    print()
    if failures:
        print(f"结果：{failures} 项失败/错误 → 退出码 1")
        return 1
    print("结果：全部通过")
    return 0


def cmd_refresh() -> int:
    print("== refresh: 先审再生 ==\n")
    audit_rc = cmd_audit()
    print()
    gen_rc = cmd_gen()
    if audit_rc or gen_rc:
        print(f"\nrefresh 完成（audit 退出码 {audit_rc}）")
        return 1 if audit_rc else gen_rc
    print("\nrefresh 完成：审计通过，生成物已刷新")
    return 0


def main(argv=None) -> int:
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass
    parser = argparse.ArgumentParser(prog="capsule.py", description="LangHuan 仓库维护胶囊工具")
    sub = parser.add_subparsers(dest="cmd", required=True)
    sub.add_parser("gen", help="刷新 capsule.yaml 机器区并重新生成 HANDOFF.md")
    sub.add_parser("audit", help="逐条校验不变量与状态查询（只读，有失败退出码 1）")
    sub.add_parser("refresh", help="先 audit 再 gen")
    args = parser.parse_args(argv)
    if args.cmd == "gen":
        return cmd_gen()
    if args.cmd == "audit":
        return cmd_audit()
    return cmd_refresh()


if __name__ == "__main__":
    raise SystemExit(main())
